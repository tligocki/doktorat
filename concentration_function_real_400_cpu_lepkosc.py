def znajdz_skrajne(tab, dlugosc=DLUGOSC_LANCUCHA, progi=PROGI_KROKU):
    """Zwraca (A, B, próg, łańcuch) albo None. A, B to wiersze tabeli okien (x0, y0, N, f, Re_A3, mu_e_pade, ...)."""
    t = tab[np.isfinite(tab['mu_e_pade'])]
    poziomy = {int(n): g.reset_index(drop=True) for n, g in t.groupby('N')}
    for L in range(dlugosc, 1, -1):
        for d in progi:
            best = None
            for n0 in sorted(poziomy):
                if any(n0 + k not in poziomy for k in range(L)):
                    continue
                lev = [poziomy[n0 + k] for k in range(L)]
                dp = np.zeros(len(lev[0]))
                prev = []
                for k in range(1, L):
                    krok = lev[k - 1]['mu_e_pade'].values[:, None] - lev[k]['mu_e_pade'].values[None, :]
                    wart = np.where(krok >= d, dp[:, None] + krok, -np.inf)
                    prev.append(wart.argmax(axis=0))
                    dp = wart.max(axis=0)
                j = int(dp.argmax())
                if np.isfinite(dp[j]) and (best is None or dp[j] > best[0]):
                    idx = [j]
                    for k in range(L - 2, -1, -1):
                        idx.append(int(prev[k][idx[-1]]))
                    idx = idx[::-1]
                    best = (float(dp[j]), [lev[k].iloc[idx[k]] for k in range(L)])
            if best is not None:
                return best[1][0], best[1][-1], d, best[1]
    return None


