# Komórka 3e (v17): współczynniki A4, A5, A6 z sum strukturalnych — dla KAŻDEGO okna
# Wzory (41), (42), (43) z: Czapla, Drygaś, Gluzman, Ligocki, Mityushev, "Computational Strategy for Analyzing
# Effective Properties of Random Composites—Part II: Elasticity", Materials 2025, 18, 5041 (plik elasticity2.tex).
# Funkcje _A4_wzor, _A5_wzor, _A6_wzor poniżej zostały WYGENEROWANE AUTOMATYCZNIE z elasticity2.tex (bez ręcznego
# przepisywania); suma e(n, j, l) = e_{n1..np}^{(j1..jp)(l1..lp)} to Def. sumy strukturalnej (wzór (33) w pracy).
# Wklej PO komórce 3d (v4) i PRZED pętlą główną (komórka 4).
# Potrzebuje: math, np (komórka 1) oraz wp_zeta_dp, lepkosc_okna, _S4, _G2, _S31, stezenie_f (komórka 3d).
#
# Co robi:
#  - sumy strukturalne dowolnego rzędu liczy jako iloczyn macierz-wektor (algorytm łańcuchowy, koszt O(p N^2)):
#        e = N^{-(alpha/2+1)} * 1^T M_1 M_2 ... M_p 1,   (M_s)_{kl} = C^{l_s} E_{n_s}^{(j_s)}(a_k - a_l),
#  - funkcje E_n (n = 2..6) i E_n^{(1)} (n = 3..6) wyraża przez zeta, p, p' (wzory Eisensteina-Natanzona-Filsztyńskiego),
#  - dodaje do wyniku każdego okna: Re/Im A4, A5, A6 oraz mu_e/mu z obcięciem szeregu na f^4, f^5, f^6.
# Wyniki trafiają do tych samych plików co dotychczas (real{i}_lepkosc_okna.csv) + nowy plik tekstowy
# real{i}_lepkosc_okna.txt (kolumny rozdzielone spacjami) — szeregi czasowe zbiera komórka 5b.

_PI = math.pi                      # (nie importujemy nazwy 'pi', żeby nie zasłonić ewentualnego pi z mpmath)

# ---------------------------------------------------------------------------------------------------------------
# PARAMETRY FIZYCZNE I KONWENCJE
# ---------------------------------------------------------------------------------------------------------------
# Parametry kontrastu rho1, rho2, rho3 (Part II, (25)): dla sztywnych inkluzji w nieściśliwej cieczy lepkiej
# (bakterie = sztywne koła, kappa = kappa1 = 1, m = eta1/eta -> inf) wszystkie trzy są równe 1.
RHO1 = RHO2 = RHO3 = 1.0
KAPPA = 1.0                       # mu_e/mu = (1 + s)/(1 - KAPPA s),  s = Re sum_k A^(k) f^k
S2_E2 = 0.0                       # S2 w E2 = wp + S2: Part II (A9) "S2 = 0 must be assumed" (liczy się tylko gdy RHO1 != RHO3)
DIAG_E31 = 0.0                    # E3^(1)(0) := 0 (jak w v16 i Part II (27)); definicja sumy ma S3^(1) = _S31 (do eksperymentów)
LICZ_A456 = True                  # False: komórka nie zmienia wyników v16


# ---------------------------------------------------------------------------------------------------------------
# FUNKCJE E_n i E_n^(1)
# ---------------------------------------------------------------------------------------------------------------
# E_n = (-1)^n/(n-1)! d^{n-2} wp/dz^{n-2},  g3 = 0 (sieć kwadratowa):
#   E3 = -wp'/2, E4 = wp^2 - g2/12, E5 = -wp wp'/2, E6 = wp^3 - 3 g2 wp/20, E7 = -wp'(wp^2/2 - g2/40).
# E_n^(1)(z) = sum_P conj(z-P)/(z-P)^n  (Eisenstein-Natanzon-Filshtinsky). Znany wzór (A7) na E3^(1) różniczkujemy po z
# (conj z jak stała): d/dz E_n^(1) = -n E_{n+1}^(1). Daje to (c = 1/pi, zb = conj z):
#   E4^(1) = zb E4 + (4c/3) E5 - (c/3) wp E3 - c zeta E4
#   E5^(1) = zb E5 + (5c/3) E6 - (c/6) E3^2 - (c/2) wp E4 - c zeta E5
#   E6^(1) = zb E6 + 2c E7 - (2c/5) E3 E4 - (3c/5) wp E5 - c zeta E6
# (sprawdzone numerycznie z bezpośrednimi sumami sieciowymi: patrz _selftest_A456()).
def macierze_E(a, xp):
    """Słownik {(n, j): macierz E_n^(j)(a_k - a_l)} dla n = 2..6; diagonala = S_n^(j)."""
    N = int(a.shape[0])
    d = a[:, None] - a[None, :]
    d = d - xp.round(d.real) - 1j * xp.round(d.imag)          # najbliższy obraz torusowy
    eye = xp.eye(N, dtype=bool)
    d = xp.where(eye, 0.3 + 0.3j, d)                           # unikamy z = 0 w szeregach
    zeta, P, Q = wp_zeta_dp(d, xp)                             # zeta, wp, wp'
    zb = xp.conj(d)
    c = 1.0 / _PI
    E3 = -Q / 2.0
    E4 = P ** 2 - _G2 / 12.0
    E5 = -P * Q / 2.0
    E6 = P ** 3 - 3.0 * _G2 * P / 20.0
    E7 = -Q * (P ** 2 / 2.0 - _G2 / 40.0)
    E = {(2, 0): P + S2_E2, (3, 0): E3, (4, 0): E4, (5, 0): E5, (6, 0): E6,
         (3, 1): (zb - c * zeta) * E3 + c * E4 - 5.0 * c * _S4 + _S31,
         (4, 1): zb * E4 + 4 * c / 3 * E5 - c / 3 * P * E3 - c * zeta * E4,
         (5, 1): zb * E5 + 5 * c / 3 * E6 - c / 6 * E3 ** 2 - c / 2 * P * E4 - c * zeta * E5,
         (6, 1): zb * E6 + 2 * c * E7 - 2 * c / 5 * E3 * E4 - 3 * c / 5 * P * E5 - c * zeta * E6}
    # wartości w zerze E_n^(j)(0) := S_n^(j); dla sieci kwadratowej S_n^(j) = 0 poza S4 i S3^(1)
    diag = {(2, 0): S2_E2, (4, 0): _S4, (3, 1): DIAG_E31}
    for klucz in E:
        E[klucz] = xp.where(eye, diag.get(klucz, 0.0), E[klucz])
    return E


def suma_strukturalna(E, n, j, l, N, xp):
    """e_{n1..np}^{(j1..jp)(l1..lp)} = N^{-(alpha/2+1)} sum_{k0..kp} prod_s C^{l_s} E_{n_s}^{(j_s)}(a_{k_{s-1}} - a_{k_s}),
    alpha = sum (n_s - j_s). Liczone jako 1^T M_1 ... M_p 1 (p mnożeń macierz x wektor)."""
    v = xp.ones(N, dtype=xp.complex128)
    for ns, js, ls in zip(reversed(n), reversed(j), reversed(l)):
        M = E[(ns, js)]
        v = (xp.conj(M) if ls else M) @ v
    alpha = sum(n) - sum(j)
    return complex(xp.sum(v)) / N ** (alpha / 2.0 + 1.0)


