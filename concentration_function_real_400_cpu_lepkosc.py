    klatki.append(dict(i=i, okien=len(t), okien_bez_mu=int((~ok).sum()), par_o_roznym_f=int(n_par),
                       par_dyskordantnych=int(n_dysk), udzial_dyskordantnych=n_dysk / max(n_par, 1),
                       spearman_f_mu=rho, okien_score_ge_5proc=int((tt['score'] >= 0.05).sum())))
