# Wzory jak w F.tex: A3 = (2/pi^2)(2 e33 + 3 e4),  Re A3 i Im A3 (e33 rzeczywiste => Im A3 = (6/pi^2) Im e4),  mu_e/mu = (1 + f + A3 f^3)/(1 - f - A3 f^3)
# Wklej PO komórce 3c i PRZED pętlą główną (komórka 4).
# Potrzebuje: math, np, pd, plt (komórka 1) oraz funkcji z 3a/3c:
