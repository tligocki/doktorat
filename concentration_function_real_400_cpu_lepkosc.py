# Stałe sieci kwadratowej o okresach 1 i i  (Part I (A5), Part II (30), (A7))
_G14  = math.gamma(0.25)
_S4   = _G14 ** 8 / (960 * math.pi ** 2)      # 3.151211
_G2   = 60.0 * _S4                             # 189.0727
_S31  = _G14 ** 8 / (384 * math.pi ** 3)      # S3^(1) = 2.50765
_QNOM = math.exp(-math.pi)                     # nome dla tau = i


# =====================================================================
# FUNKCJE ELIPTYCZNE (szereg theta; xp = numpy albo cupy)
# =====================================================================
def wp_zeta_dp(z, xp):
    """zeta, wp, wp' sieci kwadratowej (okresy 1, i). |Re z|,|Im z| <= 0.5 (najbliższy obraz)."""
    u = math.pi * z
    t0 = t1 = t2 = t3 = 0 * u
    for n in range(8):
        a = 2 * n + 1
        c = 2.0 * (-1) ** n * _QNOM ** ((n + 0.5) ** 2)
        s, co = xp.sin(a * u), xp.cos(a * u)
        t0 = t0 + c * s
        t1 = t1 + c * a * co
        t2 = t2 - c * a ** 2 * s
        t3 = t3 - c * a ** 3 * co
    L1 = t1 / t0
    L2 = t2 / t0 - L1 ** 2
    L3 = t3 / t0 - t2 * t1 / t0 ** 2 - 2 * L1 * L2
    zeta = math.pi * z + math.pi * L1
    wp = -math.pi - math.pi ** 2 * L2
    dwp = -math.pi ** 3 * L3
    return zeta, wp, dwp


# =====================================================================
# SUMY STRUKTURALNE e33^{(1,1)(1,0)} i e4^{(0)(1)}  (Part II: (39), (40), (A7))
# =====================================================================
def sumy_e33_e4(a, xp):
    """a: zespolone położenia środków w kwadracie jednostkowym (1-D). Zwraca (e33, Re e4, Im e4)."""
    N = int(a.shape[0])
    d = a[:, None] - a[None, :]
    d = d - xp.round(d.real) - 1j * xp.round(d.imag)          # najbliższy obraz torusowy
    eye = xp.eye(N, dtype=bool)
    d = xp.where(eye, 0.3 + 0.3j, d)                           # unikamy z=0 w szeregach
    zeta, wp, dwp = wp_zeta_dp(d, xp)

    E3 = -dwp / 2.0
    E4 = wp ** 2 - _G2 / 12.0                                  # = wp''/6
    E31 = (xp.conj(d) - zeta / math.pi) * E3 + E4 / math.pi - 5.0 * _S4 / math.pi + _S31
    E31 = xp.where(eye, 0.0, E31)                              # E3^(1)(0) := 0
    E4 = xp.where(eye, _S4, E4)                                # E4(0)    := S4

    e33 = float(xp.sum(xp.abs(xp.sum(E31, axis=1)) ** 2)) / N ** 3   # F.tex (11): bez znaku minus
    e4 = complex(xp.sum(E4)).conjugate() / N ** 3              # F.tex (12): e4^(0)(1) = (1/N^3) sum conj(E4)
    return e33, e4.real, e4.imag


def stezenie_f(N, r_px=None):
    r_px = R_BAKT if r_px is None else r_px
    return N * math.pi * (r_px / x_d) ** 2                     # kwadrat jednostkowy: r = r_px / 220


def mu_eff_szereg(f):
    return sum(c * f ** k for k, c in enumerate(MU_COEF))


def lepkosc_okna(a, xp):
    """Jedno okno: e33, Re e4, Re A3, f, mu_e/mu wg F.tex.
    (13): A3 = (2/pi^2)(2 e33 + 3 e4');  (14): mu_e/mu = (1+s)/(1-s), s = f + A3 f^3;
    mu_e_wz15: wzór (15) z F.tex, s = f + (e33 + e4') f^3 (tylko porównawczo)."""
    N = int(a.shape[0])
    if N < MIN_N_OKNA:
        return None
    e33, e4r, e4i = sumy_e33_e4(a, xp)
    A3 = 2.0 / math.pi ** 2 * (2.0 * e33 + 3.0 * e4r)          # Re A3 (e33 jest rzeczywiste)
    A3_im = 6.0 / math.pi ** 2 * e4i                           # Im A3 = (2/pi^2) * 3 * Im e4
    f = stezenie_f(N)
    s = f + A3 * f ** 3
    mu = (1.0 + s) / (1.0 - s) if s < 1.0 else float('nan')
    s15 = f + (e33 + e4r) * f ** 3
    mu15 = (1.0 + s15) / (1.0 - s15) if s15 < 1.0 else float('nan')
    return dict(N=N, f=f, e33=e33, Re_e4=e4r, Im_e4=e4i, Re_A3=A3, Im_A3=A3_im,
                mu_e_pade=mu, mu_e_wz15=mu15, mu_e_szereg=mu_eff_szereg(f))


