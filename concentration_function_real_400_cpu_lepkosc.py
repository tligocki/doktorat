# =====================================================================
# PARAMETRY
# =====================================================================
R_BAKT        = 3.5    # <-- r_px: promień bakterii [px] używany w f (zmieniaj ręcznie).
                       # Wzory F.tex (rozwinięcie dla nienakładających się kół) mają sens, gdy 2*r_px <= minimalny
                       # odstęp środków (czyszczenie: r_min = 8 / DIST_SCALANIE = 10 px), czyli r_px <= ok. 4.
N_WYSOKIE     = 2      # ile miejsc o wysokim N
N_NISKIE      = 2      # ile miejsc o niskim N
