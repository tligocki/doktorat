# Okna o identycznym f (ten sam N) pomijamy: f zależy tylko od N, więc przy tym samym N różnice mu wynikają
# wyłącznie z ułożenia bakterii (A3) i nie są "anomalią f–mu".
# score okna = udział okien o innym f, z którymi to okno tworzy parę dyskordantną (0 = zgodne ze wszystkimi).

import os
import numpy as np
import pandas as pd
import matplotlib.pyplot as plt

TOP_OKIEN       = 20     # tyle najbardziej dyskordantnych okien na klatkę zapisujemy do CSV
TOP_KLATEK_MAPY = 5      # dla tylu klatek (największy udział dyskordantnych par) rysujemy mapę
EPS_F           = 1e-12  # tolerancja: f traktujemy jako równe, gdy |Δf| <= EPS_F

klatki, okna_top, mapy = [], [], {}
