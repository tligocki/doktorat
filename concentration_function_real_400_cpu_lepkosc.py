MIN_N_OKNA    = 3      # okna z mniejszą liczbą punktów pomijamy

# Wzór (1) z pracy ECMS 2024 (sztywne koła, losowo) — porównawczo
MU_COEF = [1.0, 2.0, 2.0, 3.8114, 8.2731, 5.3345, 20.5096]

