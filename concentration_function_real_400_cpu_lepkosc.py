# WYBÓR MIEJSC I RYSOWANIE
# =====================================================================
def _wybierz_ekstrema(Xg, Yg, Zg, n_wys, n_nis, dmin):
    """Zachłannie n_wys najwyższych i n_nis najniższych punktów pola, każdy >= dmin od poprzednich."""
    xs, ys, zs = Xg.ravel(), Yg.ravel(), Zg.ravel()
    kolejnosc = np.argsort(zs)

    def zachlannie(order, n):
        wybrane = []
        for k in order:
            if all(np.hypot(xs[k] - qx, ys[k] - qy) >= dmin for qx, qy in wybrane):
                wybrane.append((float(xs[k]), float(ys[k])))
            if len(wybrane) == n:
                break
        return wybrane

    return zachlannie(kolejnosc[::-1], n_wys), zachlannie(kolejnosc, n_nis)


def _wiersz_okna(tab, px, py):
    """Wiersz tabeli okien najbliższy (x0, y0) = (px, py)."""
    d = (tab['x0'] - px) ** 2 + (tab['y0'] - py) ** 2
    return tab.loc[d.idxmin()]


