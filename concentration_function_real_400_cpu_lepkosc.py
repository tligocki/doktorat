def _selftest_A456(verbose=True):
    import itertools
    rng = np.random.default_rng(12345)
    wyniki = []

    def ok(nazwa, warunek, info=''):
        wyniki.append(bool(warunek))
        if verbose:
            print(f"  [{'PASS' if warunek else 'FAIL'}] {nazwa} {info}")

    # 1. E_n^(1) i E_n z wzorów zamkniętych = bezpośrednie sumy sieciowe (n >= 4: szereg zbieżny bezwzględnie)
    z0 = np.array([0.23 + 0.11j, -0.31 + 0.40j])
    E = macierze_E(np.array([0.0, 0.23 + 0.11j, -0.31 + 0.40j]), np)
    m = np.arange(-120, 121)
    P = (m[:, None] + 1j * m[None, :]).ravel()
    for (n, j) in [(4, 0), (5, 0), (6, 0), (4, 1), (5, 1), (6, 1)]:
        blad = 0.0
        for k, zz in enumerate(z0):
            w = zz - P
            bezp = np.sum(np.conj(w) ** j / w ** n)
            blad = max(blad, abs(E[(n, j)][k + 1, 0] - bezp) / max(1.0, abs(bezp)))
        ok(f"E_{n}^({j}) = suma sieciowa", blad < 1e-3, f"(błąd wzgl. {blad:.1e})")

    # 2. algorytm łańcuchowy = sumowanie wprost (p = 3, mały N)
    N = 5
    a = rng.random(N) + 1j * rng.random(N)
    E = macierze_E(a, np)
    klucz = ((3, 4, 3), (1, 0, 1), (1, 0, 1))
    dd = a[:, None] - a[None, :]
    wprost = 0j
    for k in itertools.product(range(N), repeat=4):
        t = 1 + 0j
        for s_, (ns, js, ls) in enumerate(zip(*klucz)):
            v = E[(ns, js)][k[s_], k[s_ + 1]]
            t *= np.conj(v) if ls else v
        wprost += t
    wprost /= N ** ((sum(klucz[0]) - sum(klucz[1])) / 2.0 + 1.0)
    lanc = suma_strukturalna(E, *klucz, N, np)
    ok("łańcuch macierzowy = suma po wszystkich krotkach", abs(lanc - wprost) < 1e-9 * max(1, abs(wprost)),
       f"({abs(lanc - wprost):.1e})")

    # 3. zgodność z e33, e4 z komórki 3d
    N = 40
    a = rng.random(N) + 1j * rng.random(N)
    E = macierze_E(a, np)
    e33_ref, e4r_ref, e4i_ref = sumy_e33_e4(a, np)
    e33 = suma_strukturalna(E, (3, 3), (1, 1), (1, 0), N, np)
    e4 = suma_strukturalna(E, (4,), (0,), (1,), N, np)
    ok("e33 = sumy_e33_e4 (v16)", abs(e33 - e33_ref) < 1e-9 * abs(e33_ref), f"({e33:.6g} vs {e33_ref:.6g})")
    ok("e4  = sumy_e33_e4 (v16)", abs(e4 - complex(e4r_ref, e4i_ref)) < 1e-9 * abs(e4))

    # 4. niezmienniczość względem przesunięcia wszystkich punktów (okresowość E_n^(j) i poprawność sprzężeń)
    A0 = wspolczynniki_A456(a, np)
    przes = a + (0.37 + 0.21j)
    przes = (przes.real % 1.0) + 1j * (przes.imag % 1.0)
    A1 = wspolczynniki_A456(przes, np)
    for k in ('A4', 'A5', 'A6'):
        ok(f"{k} niezmiennicze względem przesunięcia", abs(A0[k] - A1[k]) < 1e-7 * max(1.0, abs(A0[k])),
           f"({A0[k]:.6g})")

    # 5. dla rho1 = rho3 pominięcie sum z E2 nie zmienia wyniku
    Ad = wspolczynniki_A456(a, np, 0.8, 0.5, 0.8)
    E = macierze_E(a, np)
    N = len(a)
    cache = {}

    def e_pelne(n, j, l):
        if (n, j, l) not in cache:
            cache[(n, j, l)] = suma_strukturalna(E, n, j, l, N, np)
        return cache[(n, j, l)]
    ok("pominięcie E2 dla rho1 = rho3", abs(_A6_wzor(e_pelne, _RE, 0.8, 0.5, 0.8) - Ad['A6']) < 1e-9 * abs(Ad['A6']))
    if verbose:
        print("  PASS" if all(wyniki) else "  UWAGA: są błędy!", f"({sum(wyniki)}/{len(wyniki)} testów)")
    return all(wyniki)


