    """Macierz p_weierstrass(z) BEZ dodatkowej π (diagonala = 0).
    ZMIANA: liczone wektorowo w pfast.py (ta sama formuła theta, stałe sieci liczone raz)
    zamiast element po elemencie w mpmath. block_cpu nieużywany (zgodność wywołań)."""
    from pfast import p_weierstrass_matrix_fast
    return p_weierstrass_matrix_fast(z, g2=g2, g3=g3)


