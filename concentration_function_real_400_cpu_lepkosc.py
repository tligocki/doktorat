def _RE(z):
    return complex(z).real


def wspolczynniki_A456(a, xp, rho1=None, rho2=None, rho3=None):
    """Zwraca dict zespolonych A4, A5, A6 dla położeń a (1-D, zespolone, kwadrat jednostkowy)."""
    rho1 = RHO1 if rho1 is None else rho1
    rho2 = RHO2 if rho2 is None else rho2
    rho3 = RHO3 if rho3 is None else rho3
    N = int(a.shape[0])
    E = macierze_E(a, xp)
    pomin_E2 = (rho1 == rho3)           # wszystkie sumy z n=2 mnożą się przez (rho1 - rho3): wtedy je pomijamy
    cache = {}

    def e(n, j, l):
        klucz = (n, j, l)
        if klucz not in cache:
            cache[klucz] = 0j if (pomin_E2 and 2 in n) else suma_strukturalna(E, n, j, l, N, xp)
        return cache[klucz]

    return dict(A4=_A4_wzor(e, _RE, rho1, rho2, rho3),
                A5=_A5_wzor(e, _RE, rho1, rho2, rho3),
                A6=_A6_wzor(e, _RE, rho1, rho2, rho3))


