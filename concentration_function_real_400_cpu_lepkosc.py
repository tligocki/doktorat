# Ten sam tor obliczeń co dla okien z rzeczywistych klatek (komórki 3b/3d):
#   punkty (px) -> /x_d, /y_d -> a = x + i*y w kwadracie jednostkowym -> lepkosc_okna(a, xp)
#   (f = N*pi*(R_BAKT/x_d)^2, sumy e33, e4, Re A3, mu_e/mu = (1+s)/(1-s), s = f + A3 f^3).
# Losowanie jest zgodne z warunkami, które spełniają punkty po czyszczeniu w prepare():
#   - odległość torusowa każdych dwóch środków >= r_min (usun_duplikaty_torus),
#   - każdy środek w osobnej komórce siatki DIST_SCALANIE x DIST_SCALANIE px (kwantyzuj_do_siatki
#     nie scala wtedy punktów i nie zmienia ich położeń, więc N pozostaje dokładnie równe zadanemu).
# Wklej PO komórce 3d (funkcja lepkosc_okna) — może być przed lub po pętli głównej (komórka 4).

PRZYPADKI_8   = {'C': 39, 'D': 43}   # liczby losowych bakterii w oknie
SEED_8        = 1                    # ziarno generatora (zmień, aby uzyskać inną realizację)
MAX_PROB_8    = 200_000              # limit prób losowania pojedynczego punktu
ZAPISZ_8      = True                 # zapis CSV i PNG do PATH_CSV
NORMUJ_OSIE_8 = True                 # True: osie x, y w [0, 1] (jak Figure 1); False: w pikselach

try:
    xp8 = cp                         # GPU (jak w prepare()), jeśli CuPy jest zaimportowane
except NameError:
    xp8 = np


def losuj_punkty_okna(N, rng, y_d=y_d, x_d=x_d, r_min=r_min, krok=DIST_SCALANIE):
    """N punktów jednostajnie w oknie x_d x y_d [px] (torus), spełniających warunki czyszczenia."""
    pts = np.empty((0, 2))
    komorki = set()
    proby = 0
    while len(pts) < N:
        proby += 1
        if proby > MAX_PROB_8:
            raise RuntimeError(f"Nie udało się wylosować {N} punktów (po {MAX_PROB_8} próbach).")
        p = np.array([rng.uniform(0, y_d), rng.uniform(0, x_d)])          # (y, x) jak w prepare()
        kom = (int(p[0] // krok), int(p[1] // krok))
        if kom in komorki:
            continue
        if len(pts):
            d = np.abs(pts - p)
            d = np.minimum(d, np.array([y_d, x_d]) - d)                   # odległość torusowa
            if np.min(np.hypot(d[:, 0], d[:, 1])) < r_min:
                continue
        pts = np.vstack([pts, p])
        komorki.add(kom)
    return pts


rng8 = np.random.default_rng(SEED_8)
